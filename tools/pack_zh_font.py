"""Generate platforms/passport/main/ui/zh_font.h: the Source Han Sans SC
Regular subset (12 px, 4 bpp) covering printable ASCII and every non-ASCII
character in the UI sources. Same font, size and glyph format as ../Spartan/tools/pack_zh_font.py, but
rasterized by tools/zh_glyphs.c (LVGL's stb_truetype, built with the Zig
toolchain the host tests use), so no Python packages are needed."""
import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

root = Path(__file__).resolve().parents[1]
name = 'SourceHanSansSC-Regular.otf'
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--font', type=Path)
p.add_argument('--zig', type=Path, default=root.parent / 'Spartan/build/host-tools/ziglang/zig.exe')
p.add_argument('--lvgl', type=Path, default=root / 'managed_components/lvgl__lvgl')
a = p.parse_args()
lvgl = a.lvgl if (a.lvgl / 'lvgl.h').exists() else root.parent / 'Spartan/managed_components/lvgl__lvgl'
font_path = a.font or next((f for f in (root / 'assets/fonts' / name, root.parent / 'Spartan/assets/fonts' / name)
                            if f.exists()), None)
if not font_path or not font_path.exists():
    raise SystemExit(f'{name} not found: pass --font')
sources = sorted((root / 'platforms/passport/main/ui').glob('*.c'))
chars = sorted({ord(c) for p in sources for c in p.read_text(encoding='utf-8') if ord(c) > 127} | set(range(32, 127)))
assert max(chars) - min(chars) < 65536
with tempfile.TemporaryDirectory() as tmp:
    tmp = Path(tmp)
    exe = tmp / ('zh_glyphs' + ('.exe' if sys.platform == 'win32' else ''))
    target = 'x86_64-windows-gnu' if sys.platform == 'win32' else 'native'
    subprocess.run([str(a.zig), 'cc', '-O2', '-target', target, f'-I{lvgl}', str(root / 'tools/zh_glyphs.c'),
                    '-o', str(exe)], check=True)
    (tmp / 'codepoints.txt').write_text('\n'.join(map(str, chars)), encoding='ascii')
    subprocess.run([str(exe), str(font_path), str(tmp / 'codepoints.txt'), str(tmp / 'glyphs.bin')], check=True)
    raw = (tmp / 'glyphs.bin').read_bytes()
bitmaps = []
descriptors = ['{0}']
pos = 0
for code in chars:
    width = raw[pos]
    cells = raw[pos + 1:pos + 1 + width * 12]
    pos += 1 + width * 12
    values = [(v * 15 + 127) // 255 for v in cells]
    if len(values) % 2:
        values.append(0)
    offset = len(bitmaps)
    bitmaps.extend((values[i] << 4) | values[i + 1] for i in range(0, len(values), 2))
    descriptors.append(f'{{.bitmap_index={offset},.adv_w={width * 16},.box_w={width},.box_h=12,.ofs_x=0,.ofs_y=-2}}')


def rows(xs, fmt, n):
    return '\n'.join('    ' + ','.join(fmt(x) for x in xs[i:i + n]) + ',' for i in range(0, len(xs), n))


output = ('/* Generated by tools/pack_zh_font.py from Source Han Sans SC Regular, SIL OFL 1.1;\n'
          '   see assets/fonts/SourceHanSansSC-OFL-1.1.txt. Included once, by lang.c. */\n'
          '#include "src/font/fmt_txt/lv_font_fmt_txt.h"\n'
          'static const uint8_t gd_zh_bitmap[]={\n' + rows(bitmaps, lambda x: f'0x{x:02x}', 24) + '\n};\n'
          'static const lv_font_fmt_txt_glyph_dsc_t gd_zh_glyphs[]={\n' + ',\n'.join(descriptors) + '\n};\n'
          'static const uint16_t gd_zh_unicode[]={\n' + rows([c - chars[0] for c in chars], str, 16) + '\n};\n'
          f'static const lv_font_fmt_txt_cmap_t gd_zh_cmap[]={{ {{.range_start={chars[0]},'
          f'.range_length={chars[-1] - chars[0] + 1},.glyph_id_start=1,.unicode_list=gd_zh_unicode,'
          f'.list_length={len(chars)},.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}} }};\n'
          'static const lv_font_fmt_txt_dsc_t gd_zh_font_data={.glyph_bitmap=gd_zh_bitmap,.glyph_dsc=gd_zh_glyphs,'
          '.cmaps=gd_zh_cmap,.cmap_num=1,.bpp=4};\n'
          'const lv_font_t gd_zh_font={.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,'
          '.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height=14,.base_line=2,.dsc=&gd_zh_font_data};\n')
(root / 'platforms/passport/main/ui/zh_font.h').write_text(output, encoding='utf-8', newline='\n')
print('Chinese font:', len(chars), 'glyphs,', len(bitmaps), 'bitmap bytes')
